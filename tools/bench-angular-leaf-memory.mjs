#!/usr/bin/env node
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const argument = (name, fallback) => {
  const index = process.argv.indexOf(name);
  return index === -1 ? fallback : process.argv[index + 1];
};

const sourceArgument = (name) => {
  const value = argument(name, '');
  if (!value || value.startsWith('--') || !/\bsha256:[a-f\d]{64}\b/.test(value)) {
    throw new Error(`Provide ${name} with a full SHA-256 digest`);
  }
  return value;
};
const samples = Number(argument('--samples', 5));
const leafCount = Number(argument('--leaves', 100_000));
const observedCount = Number(argument('--observed', 10_000));
const roots = [
  {
    label: argument('--a-label', 'current'),
    root: argument('--a-root', ''),
    mode: argument('--a-mode', 'location'),
    source: sourceArgument('--a-source'),
  },
  {
    label: argument('--b-label', 'candidate'),
    root: argument('--b-root', ''),
    mode: argument('--b-mode', 'location'),
    source: sourceArgument('--b-source'),
  },
];
if (roots.some((entry) => !entry.root)) throw new Error('Provide --a-root and --b-root');

const median = (values) => {
  const ordered = [...values].sort((left, right) => left - right);
  return ordered[Math.floor(ordered.length / 2)];
};

const run = (root, mode, observed) => {
  const output = execFileSync(
    process.execPath,
    [
      '--expose-gc',
      resolve('tools/bench-angular-leaf-memory-worker.mjs'),
      '--consumer-root',
      root,
      '--mode',
      mode,
      '--leaves',
      String(leafCount),
      '--observed',
      String(observed),
    ],
    { encoding: 'utf8' }
  );
  return JSON.parse(output.trim().split('\n').at(-1));
};

const results = [];
for (const observed of [0, observedCount]) {
  for (const entry of roots) {
    const runs = Array.from({ length: samples }, () =>
      run(entry.root, entry.mode, observed)
    );
    results.push({
      label: entry.label,
      leafCount,
      observedCount: observed,
      retainedMB: median(runs.map((result) => result.retainedMB)),
      bytesPerLeaf: median(runs.map((result) => result.bytesPerLeaf)),
      collectable: runs.every(
        (result) => result.collectable.tree && result.collectable.leaf
      ),
      samples: runs,
    });
  }
}

const output = {
  schemaVersion: 1,
  method: 'isolated-process-forced-gc-angular-leaf-memory-v1',
  runtime: {
    node: process.version,
    platform: process.platform,
    architecture: process.arch,
  },
  config: { samples, leafCount, observedCount },
  arms: roots.map(({ label, mode, source }) => ({ label, mode, source })),
  results,
};

const outputPath = argument('--output');
if (outputPath) {
  writeFileSync(resolve(outputPath), `${JSON.stringify(output, null, 2)}\n`);
}

const typescriptOutputPath = argument('--typescript-output');
if (typescriptOutputPath) {
  const exportName = argument('--export-name', 'ANGULAR_LEAF_MEMORY_BENCHMARK');
  if (!/^[A-Z][A-Z0-9_]*$/.test(exportName)) {
    throw new Error('--export-name must be an uppercase TypeScript identifier');
  }
  writeFileSync(
    resolve(typescriptOutputPath),
    `// Generated by tools/bench-angular-leaf-memory.mjs. Do not edit.\n` +
      `export const ${exportName} = ${JSON.stringify(output, null, 2)} as const;\n`
  );
}

console.log(JSON.stringify(output, null, 2));
