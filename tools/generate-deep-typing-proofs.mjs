#!/usr/bin/env node

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const prettier = require('prettier');
const GENERATED_DIRECTORY = resolve(
  ROOT,
  'apps/demo/src/app/components/extreme-depth'
);
const CATALOG_TARGET = resolve(
  GENERATED_DIRECTORY,
  'deep-typing-catalog.generated.ts'
);
const PROOFS_TARGET = resolve(
  GENERATED_DIRECTORY,
  'deep-typing-proofs.generated.typecheck.ts'
);
const MIN_DEPTH = 1;
const MAX_DEPTH = 40;
const BASE_SEGMENTS = [
  'enterprise',
  'divisions',
  'technology',
  'departments',
  'engineering',
  'teams',
  'frontend',
  'projects',
  'signaltree',
  'releases',
  'v15',
  'features',
  'recursiveTyping',
  'validation',
];
const BRANCH_SEGMENTS = Array.from(
  { length: MAX_DEPTH - 1 },
  (_, index) =>
    BASE_SEGMENTS[index] ?? `branch${String(index + 1).padStart(2, '0')}`
);
const DEPTHS = Array.from(
  { length: MAX_DEPTH - MIN_DEPTH + 1 },
  (_, index) => index + MIN_DEPTH
);

const indent = (level) => '  '.repeat(level);
const format = (source, filepath) =>
  prettier.format(source, {
    ...(prettier.resolveConfig.sync(filepath) ?? {}),
    filepath,
  });

const renderInitialState = (segments, level = 0) => {
  const [segment, ...rest] = segments;
  const value =
    rest.length === 0
      ? `{
${indent(level + 2)}status: 'ready' as DeepTypingStatus,
${indent(level + 2)}revision: 1,
${indent(level + 2)}owner: 'application',
${indent(level + 1)}}`
      : renderInitialState(rest, level + 1);
  return `{
${indent(level + 1)}${segment}: ${value},
${indent(level)}}`;
};

const renderDepthProof = (depth) => {
  const pathSegments = [...BRANCH_SEGMENTS.slice(0, depth - 1), 'result'];
  const suffix = String(depth).padStart(2, '0');
  const initialState = renderInitialState(pathSegments);
  const access = pathSegments.map((segment) => `['${segment}']`).join('');

  return `const _createGeneratedDepth${suffix}Tree = () => signalTree(${initialState});
type GeneratedDepth${suffix}Leaf = ReturnType<typeof _createGeneratedDepth${suffix}Tree>['$']${access}['status'];
type GeneratedDepth${suffix}Check = readonly [
  Expect<Equal<GeneratedDepth${suffix}Leaf, WritableLeaf<DeepTypingStatus>>>,
  Expect<Equal<IsAny<GeneratedDepth${suffix}Leaf>, false>>,
];
void _createGeneratedDepth${suffix}Tree;`;
};

const catalog = format(
  `// AUTO-GENERATED FILE. DO NOT EDIT MANUALLY.
// Generated by tools/generate-deep-typing-proofs.mjs.

export type DeepTypingStatus = 'ready' | 'review';

export const DEEP_TYPING_COMPILED_DEPTHS = [${DEPTHS.join(', ')}] as const;
export type DeepTypingCompiledDepth =
  (typeof DEEP_TYPING_COMPILED_DEPTHS)[number];
export const DEEP_TYPING_MIN_DEPTH: DeepTypingCompiledDepth = ${MIN_DEPTH};
export const DEEP_TYPING_MAX_DEPTH: DeepTypingCompiledDepth = ${MAX_DEPTH};
export const DEEP_TYPING_COMPILER_CHECKS = {
  exactLeafCarrier: true,
  isAny: false,
} as const;
export const DEEP_TYPING_BRANCH_SEGMENTS = ${JSON.stringify(
    BRANCH_SEGMENTS
  )} as const;

export const isDeepTypingCompiledDepth = (
  value: number
): value is DeepTypingCompiledDepth =>
  Number.isInteger(value) &&
  value >= DEEP_TYPING_MIN_DEPTH &&
  value <= DEEP_TYPING_MAX_DEPTH;
`,
  CATALOG_TARGET
);

const proofs = format(
  `// AUTO-GENERATED COMPILE-ONLY FILE. DO NOT IMPORT AT RUNTIME.
// Generated by tools/generate-deep-typing-proofs.mjs.

import { signalTree, type WritableLeaf } from '@signal-tree/angular';
import type { DeepTypingStatus } from './deep-typing-catalog.generated';

type Equal<Left, Right> = (<Value>() => Value extends Left ? 1 : 2) extends <
  Value
>() => Value extends Right ? 1 : 2
  ? true
  : false;
type Expect<Value extends true> = Value;
type IsAny<Value> = 0 extends 1 & Value ? true : false;

${DEPTHS.map(renderDepthProof).join('\n\n')}

export type GeneratedDeepTypingChecks = readonly [
${DEPTHS.map(
  (depth) => `  GeneratedDepth${String(depth).padStart(2, '0')}Check,`
).join('\n')}
];
`,
  PROOFS_TARGET
);

const OUTPUTS = [
  [CATALOG_TARGET, catalog],
  [PROOFS_TARGET, proofs],
];

const staleOutputs = () =>
  OUTPUTS.filter(([path, expected]) => {
    try {
      return readFileSync(path, 'utf8') !== expected;
    } catch {
      return true;
    }
  });

const check = () => {
  const stale = staleOutputs();
  if (stale.length > 0) {
    console.error(
      `Deep-typing generated files are stale: ${stale
        .map(([path]) => path.slice(ROOT.length + 1))
        .join(', ')}. Run: node tools/generate-deep-typing-proofs.mjs`
    );
    return false;
  }

  console.log(
    `Deep-typing generated files are current (${MIN_DEPTH}-${MAX_DEPTH}).`
  );
  return true;
};

if (process.argv.includes('--self-test')) {
  const originals = OUTPUTS.map(([path]) => [path, readFileSync(path, 'utf8')]);
  try {
    writeFileSync(CATALOG_TARGET, `${catalog}\n// deliberate drift\n`, 'utf8');
    let rejected = false;
    try {
      execFileSync(
        process.execPath,
        [fileURLToPath(import.meta.url), '--check'],
        {
          cwd: ROOT,
          stdio: 'pipe',
        }
      );
    } catch {
      rejected = true;
    }
    if (!rejected) {
      console.error(
        'Deep-typing checker accepted a deliberately stale catalog.'
      );
      process.exitCode = 1;
    } else {
      console.log('Deep-typing checker rejected a deliberately stale catalog.');
    }
  } finally {
    for (const [path, original] of originals) {
      writeFileSync(path, original, 'utf8');
    }
  }
} else if (process.argv.includes('--check')) {
  if (!check()) process.exitCode = 1;
} else {
  for (const [path, contents] of OUTPUTS) {
    writeFileSync(path, contents, 'utf8');
  }
  console.log(
    `Generated deep-typing proofs for depths ${MIN_DEPTH}-${MAX_DEPTH}.`
  );
}
